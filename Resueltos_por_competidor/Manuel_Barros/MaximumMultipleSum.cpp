#include <iostream>
typedef long long ll;
using namespace std;

int main()
{
    ios_base::sync_with_stdio(0);
    cin.tie(0);

    ll t;
    cin >> t;
    while(t--){
        ll a;
        cin >> a;
        if(a == 3){
            cout << 3 << "\n";
        }
        else{
            cout << 2 << "\n";
        }
    }
}
